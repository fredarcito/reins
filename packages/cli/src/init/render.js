// Text output of `reins init`: the architecture.yml draft and the review report (markdown).

const q = (s) => JSON.stringify(s); // a JSON string is a valid YAML scalar
const key = (s) => (/^[A-Za-z_][\w-]*$/.test(s) ? s : q(s));
const list = (xs) => `[${xs.map(q).join(', ')}]`;

/**
 * @param {{ adapters: string[], preset: string | null, date: string, layers: { name: string, paths: string[] }[],
 *   domains: { name: string, paths: string[], publicApi: string[] }[], ignoreKinds: string[], adapterRules: string[] }} d
 *   `preset`: null with several adapters (each one detects its own); `ignoreKinds`: edge kinds the rules ignore
 */
export function renderArchitecture(d) {
  const ignore = d.ignoreKinds.length ? `, ignore_kinds: [${d.ignoreKinds.map(key).join(', ')}]` : '';
  const lines = [
    `# Draft generated by \`reins init\` on ${d.date}.`,
    '# The code shows what exists, not what should exist: review layers and domains before committing.',
    '# Reference: docs/architecture-yml.md in reins repo.',
    'version: 1',
    `adapters: [${d.adapters.map(key).join(', ')}]`,
    ...(d.preset ? [`preset: ${key(d.preset)}`] : []),
    '',
    '# Top to bottom: a layer may only import from itself and the layers below it.',
    d.layers.length ? 'layers:' : 'layers: []',
    ...d.layers.map((l) => `  - { name: ${key(l.name)}, paths: ${list(l.paths)} }`),
    '',
    '# Code outside a domain may only import its public_api.',
    d.domains.length ? 'domains:' : 'domains: {}',
    ...d.domains.map((x) => `  ${key(x.name)}: { paths: ${list(x.paths)}, public_api: ${list(x.publicApi)} }`),
    '',
    'rules:',
    `  - { id: layer-direction, severity: error${ignore} }`,
    `  - { id: domain-boundary, severity: error${ignore} }`,
    `  - { id: no-cycles, severity: error${ignore} }`,
    '  - { id: integrity, severity: warn }',
    ...d.adapterRules.map((r) => `  - { id: ${key(r)}, severity: warn }`),
    '',
    '# Permanent exceptions, each with a reason. Existing mess goes in baseline.json instead.',
    'allow: []',
    '',
  ];
  return lines.join('\n');
}

const bullet = (items, empty) => (items.length ? items.map((s) => `- ${s}`).join('\n') : `- ${empty}`);
const MAX = 15;
const capped = (items) => (items.length > MAX ? [...items.slice(0, MAX), `… and ${items.length - MAX} more`] : items);

/**
 * @param {object} d
 * @param {string} d.date
 * @param {{ packageName: string, preset: string | null, reason: string }[]} d.adapters
 * @param {string} d.preset
 * @param {boolean} d.detected
 * @param {ReturnType<import('./infer.js').inferLayers>} d.layerInfo
 * @param {ReturnType<import('./infer.js').inferDomains>} d.domains
 * @param {boolean} [d.fromRoutes] the domains are route folders (the repo has no domain folders)
 * @param {string[]} [d.smallRoutes] route folders left out for having too few files
 * @param {{ folder: string, domain: string, share: number, imports: number }[]} [d.doubtfulOwned]
 * @param {{ name: string, importedFrom: number, closed: boolean }[]} [d.domainFacts]
 * @param {{ violations: { rule: string, from: string, to?: string, message: string }[] }} d.result
 * @param {string[]} d.orphans
 * @param {string[]} d.warnings
 * @param {number} d.files
 * @param {number} d.edges
 * @param {{ kind: string, reason: string }[]} d.ignoredKinds
 */
export function renderReport(d) {
  const v = d.result.violations;
  const byRule = (rule) => v.filter((x) => x.rule === rule);
  const cycles = byRule('no-cycles').map((x) => x.message.replace(/^Import cycle: /, '').replace(/\.$/, ''));
  const doubtful = v.filter((x) => x.rule !== 'no-cycles').map((x) => `\`${x.rule}\` ${x.from}${x.to ? ` → ${x.to}` : ''}`);
  const counts = ['layer-direction', 'domain-boundary', 'no-cycles'].map((r) => `${r}: ${byRule(r).length}`);
  const adapterRuleCount = v.filter((x) => !['layer-direction', 'domain-boundary', 'no-cycles'].includes(x.rule)).length;
  if (adapterRuleCount) counts.push(`adapter rules: ${adapterRuleCount}`);

  return `# reins init report (${d.date})

Draft plan for this repo. **The code shows what exists, not what should exist**: a person decides the architecture.
Review this, edit \`.reins/architecture.yml\`, then run \`reins check --update-baseline\` and commit both files.

## Summary

- Adapter${d.adapters.length > 1 ? 's' : ''}: ${d.adapters.map((a) => `\`${a.packageName}\`${a.preset ? `, preset \`${a.preset}\` (${a.reason})` : ' (no preset)'}`).join('; ')}${d.detected ? '' : '. **Warning:** the adapter did not recognize this repo'}
- Scanned: ${d.files} files, ${d.edges} internal imports${d.ignoredKinds.map((k) => `; ${k.reason} (\`ignore_kinds: [${k.kind}]\`)`).join('')}
- Existing violations frozen in \`baseline.json\`: **${v.length}** (${counts.join(', ')})
- Source files outside every layer (not checked): **${d.layerInfo.unclassified.reduce((n, u) => n + u.files, 0)}**${d.layerInfo.unclassified.length ? ' — see "Folders with source files outside every layer"' : ''}

## Layers (top to bottom)

Kept from the preset when the folders exist, then ordered by the dominant direction of their imports.

| Layer | Paths | Files |
| --- | --- | --- |
${d.layerInfo.layers.map((l) => `| ${l.name} | ${l.paths.map((p) => `\`${p}\``).join(', ')} | ${l.files} |`).join('\n') || '| (none found) | | |'}

Evidence (imports going down / going up; "up" ones are layer violations):

${bullet(d.layerInfo.pairs.map((p) => `${p.above} → ${p.below}: ${p.down} down, ${p.up} up${p.up > p.down / 3 && p.up > 0 ? ' — **mixed: check this order**' : ''}`), 'no imports between layers')}
${d.layerInfo.conflicts.length ? `\n${bullet(d.layerInfo.conflicts, '')}\n` : ''}
Folders with source files outside every layer (add them to a layer, or leave them unchecked):

${bullet(capped(d.layerInfo.unclassified.map(unclassifiedLine)), 'none')}

## Domains
${d.fromRoutes ? '\nNo domain folders (e.g. `src/features/*`), so each route folder is proposed as a domain. Route groups `(x)` and parameters `[x]` are looked through, and a route folder with a single source file is left out unless it owns a folder elsewhere (e.g. `components/pages/x`). Merge or drop the ones that are not real modules (legal pages, redirects…).\n' : ''}
${bullet(d.domains.map((x) => domainLine(x, d.domainFacts?.find((f) => f.name === x.name))), 'none proposed (no folders matching the preset, e.g. `src/features/*`)')}
${d.smallRoutes?.length ? `\nRoute folders left out (a single source file that owns no folder elsewhere, e.g. a lone page, \`sitemap.xml\` or \`llms.txt\`): too small for a domain or a note; the layer rules still check them:\n\n${bullet(capped(d.smallRoutes.map((f) => `\`${f}/\``)), '')}\n` : ''}${d.doubtfulOwned?.length ? `\nFolders mostly used by one domain, but not only: not added to it, since the other imports would become violations. Add them by hand if they belong to it:\n\n${bullet(capped(d.doubtfulOwned.map((x) => `\`${x.folder}/\` → \`${x.domain}\` (${x.imports} of ${Math.round(x.imports / x.share)} imports into it come from that domain)`)), '')}\n` : ''}
## Cycles

${bullet(capped(cycles), 'none')}

## Doubtful dependencies

Imports that break the drafted plan. Either the plan is wrong (fix \`architecture.yml\`) or the code is (they stay in the baseline until fixed).

${bullet(capped(doubtful), 'none')}

## Orphans

Source files nobody imports that are not entry points, tests or config. Possibly dead code.

${bullet(capped(d.orphans.map((o) => `\`${o}\``)), 'none')}

## Warnings

${bullet(d.warnings, 'none')}

## Next steps

1. Edit \`.reins/architecture.yml\`: layer order, folders outside every layer, domains and their public API. In Claude Code, \`/reins-arch\` has your agent propose these changes with evidence; you approve each one.
2. Fill in the module notes in \`.reins/notes/\`: in Claude Code, \`/reins-notes\`; with other agents, ask them to fill in the TODO lines.
3. \`reins check --update-baseline\` to freeze the violations of the final plan.
4. \`reins check\` must pass. Commit \`.reins/\` (the pre-commit hook needs the plan, so not before).
5. This report is only for review; you don't need to commit it.
`;
}

/** One domain in the report: folder, extra folders it owns, public API, and what domain-boundary guards. */
function domainLine(x, facts) {
  const owned = x.owned?.length
    ? `; also ${x.owned.map((o) => `\`${o.folder}/\` (${o.files} files, ${o.total && o.total > o.imports ? `${o.imports} of ${o.total} imports into it come from this domain; the other ${o.total - o.imports} become violations, frozen in the baseline` : 'imported only from this domain'})`).join(', ')}`
    : '';
  const loose = x.loose?.length
    ? `; its note also covers ${x.loose.length} loose file(s) only this domain uses: ${x.loose.slice(0, 5).map((f) => `\`${f}\``).join(', ')}${x.loose.length > 5 ? ', …' : ''} (not its rules; move them into a folder to make them part of the domain)`
    : '';
  const api = `public API ${x.publicApi.map((p) => `\`${p}\``).join(', ')}`;
  let guard = '';
  if (x.missingIndex) guard = ' — **no index file: create it or change public_api**';
  else if (facts?.closed) guard = ` — closed: its public API is only route entry files, which nobody imports, so \`domain-boundary\` flags any import of its files from outside (today: ${facts.importedFrom}). Shared code belongs in a lower layer`;
  else if (facts) guard = ` — imported from outside: ${facts.importedFrom} time(s)`;
  const where = (x.folders ?? [x.folder]).map((f) => `\`${f}/\``).join(' + ');
  return `\`${x.name}\`: ${where} (${x.files} files)${owned}, ${api}${guard}${loose}`;
}

/** A folder outside every layer, with where it would fit from its imports. */
function unclassifiedLine(u) {
  const facts = [
    u.importedBy?.length ? `imported by ${u.importedBy.join(', ')}` : '',
    u.imports?.length ? `imports ${u.imports.join(', ')}` : '',
  ].filter(Boolean).join('; ');
  const fit = u.fits
    ? ` — **fits \`${u.fits}\`** (add \`${u.folder}/**\` to its paths)`
    : u.importedBy?.length || u.imports?.length ? ' — no layer fits without violations: its imports go both ways' : ' — no imports to or from the layers';
  return `\`${u.folder}/\` (${u.files} files${facts ? `; ${facts}` : ''})${fit}`;
}

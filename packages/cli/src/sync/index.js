// reins sync: updates provider-neutral core sources and AGENTS.md, plus an optional Claude Code adapter.
//
//   templates/.reins/core/** -> .reins/core/**
//   templates/.reins/<override folder>/README.md -> .reins/<override folder>/README.md (where your own versions go)
//   .reins/core/skills/<n>/ (or .reins/skills/<n>/ override) -> .claude/skills/reins-<n>/ (optional)
//   .reins/core/agents/<n>.md (or .reins/agents/<n>.md override) -> .claude/agents/reins-<n>.md (optional)
//   .reins/notes/*.md -> notes index block inside AGENTS.md
//   templates -> AGENTS.md and, when enabled, CLAUDE.md (only when missing)
//   with the Claude Code adapter: hooks in .claude/settings.json, plus a no-op sessionStart in .cursor/hooks.json
//   (Cursor runs the .claude/settings.json hooks, but only fires session start when a native hook asks for it)
//
// Everything it writes is recorded in .reins/.generated.json, and it only ever touches what is recorded there:
// third-party skills, agents and settings are never overwritten or deleted. The one exception: unmodified copies
// of defaults an older `reins install` put in .reins/ (legacy-defaults.json) are removed, since .reins/core/ replaces them.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { countLines, DOCTOR_DEFAULTS, parentNoteFile, parseFrontmatter } from '@agentreins/core';
import { ARCHITECTURE_FILE, REINS_DIR, runScriptCommand } from '../context.js';
import { loadNotes, readDoctorConfig, readText } from '../project.js';
import { readTemplate, renderAgentsMd, templatesDir } from '../templates.js';

export const MANIFEST_FILE = `${REINS_DIR}/.generated.json`;
export const SETTINGS_FILE = '.claude/settings.json';
export const CURSOR_HOOKS_FILE = '.cursor/hooks.json';
export const PREFIX = 'reins-';
/** What `reins install` appends to an AGENTS.md that has no rules block yet. */
export const RULES_BLOCK_SECTION = '<!-- reins:rules:start (generated by reins sync) -->\n<!-- reins:rules:end -->\n';
export const RULES_BLOCK_RE = /(<!-- reins:rules:start[^>]*-->\r?\n)([\s\S]*?)(<!-- reins:rules:end -->)/;
/** What `reins install` appends to an AGENTS.md that has no notes index yet. */
export const NOTES_BLOCK_SECTION = '## Module notes\n<!-- reins:notes:start (generated by reins sync) -->\n<!-- reins:notes:end -->\n';
export const NOTES_BLOCK_RE = /(<!-- reins:notes:start[^>]*-->\r?\n)([\s\S]*?)(<!-- reins:notes:end -->)/;

/** Permissions and hooks reins adds to .claude/settings.json. */
export const SETTINGS = Object.freeze({
  deny: ['Bash(git commit:*)', 'Bash(git push:*)'],
  hooks: [
    { event: 'PreToolUse', matcher: 'Read|Edit|Write|MultiEdit', command: '"$CLAUDE_PROJECT_DIR"/node_modules/.bin/reins notes --hook' },
    { event: 'SessionStart', matcher: 'startup|compact|clear', command: '"$CLAUDE_PROJECT_DIR"/node_modules/.bin/reins resume --hook' },
  ],
});

/**
 * Native Cursor hooks reins adds. Cursor runs the hooks of .claude/settings.json (reins' notes and resume hooks) but
 * only requests `sessionStart` when a native hook defines it (VERIFIED P12): this no-op entry makes it do so, and
 * the real work stays in the Claude Code SessionStart hook. Calling reins here would run resume twice in Cursor.
 */
export const CURSOR_HOOKS = Object.freeze([
  { event: 'sessionStart', command: "echo '{}' # reins: makes Cursor run the SessionStart hooks of .claude/settings.json" },
]);

const sha = (s) => createHash('sha256').update(s).digest('hex');
const posix = (p) => p.split(path.sep).join('/');
const generatedNote = (source) => `<!-- Generated by reins sync from ${source}. Edit the source and run \`reins sync\`. -->`;
const yamlScalar = (s) => (/^[\w .,()/-]+$/.test(s) && !/^\s|\s$/.test(s) ? s : JSON.stringify(s));

/** All files under a folder, repo-relative. */
function listFiles(root, rel) {
  const abs = path.join(root, rel);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const name of readdirSync(abs).sort()) {
    const r = `${rel}/${name}`;
    if (statSync(path.join(root, r)).isDirectory()) out.push(...listFiles(root, r));
    else out.push(r);
  }
  return out;
}

/** Defaults `reins install` copied into .reins/ before templates/.reins/core/ existed (<= 0.7.4), by sha256. */
const LEGACY = JSON.parse(readFileSync(new URL('./legacy-defaults.json', import.meta.url), 'utf8'));
const LEGACY_DIRS = ['skills', 'agents', 'policies', 'templates', 'review'];

/**
 * Files in .reins/{skills,agents,policies,templates,review} that are unmodified copies of a default reins shipped,
 * either a version an older `reins install` copied or the current one in .reins/core/. They are not overrides:
 * sync removes them so the synced core applies. Anything edited by hand is kept as an override.
 * @param {string} root
 * @returns {string[]}
 */
export function legacyCopies(root) {
  const coreBase = path.join(templatesDir(), REINS_DIR, 'core');
  const out = [];
  for (const dir of LEGACY_DIRS) {
    for (const f of listFiles(root, `${REINS_DIR}/${dir}`)) {
      const text = readFileSync(path.join(root, f), 'utf8');
      const core = path.join(coreBase, f.slice(REINS_DIR.length + 1));
      if ((LEGACY.files[f] ?? []).includes(sha(text)) || (existsSync(core) && readFileSync(core, 'utf8') === text)) out.push(f);
    }
  }
  return out;
}

/**
 * AGENTS.md with the rules an older reins template wrote ("## Always" up to the notes block, unedited) replaced by
 * empty rules markers that sync then fills. Null when there are markers already or the rules are not a shipped version.
 * @param {string} agents
 * @returns {string | null}
 */
export function migrateLegacyRules(agents) {
  if (RULES_BLOCK_RE.test(agents)) return null;
  const start = agents.indexOf('\n## Always\n');
  const end = agents.indexOf('<!-- reins:notes:start');
  if (start < 0 || end <= start || !LEGACY.agentsRules.includes(sha(agents.slice(start + 1, end)))) return null;
  return `${agents.slice(0, start + 1)}${RULES_BLOCK_SECTION}\n${agents.slice(end)}`;
}

/** `adapter: js` (reins <= 0.11.0), alone on its line, with an optional comment. */
const OLD_ADAPTER_KEY_RE = /^adapter:[ \t]*(["']?)([\w-]+)\1([ \t]*#.*)?$/m;

/**
 * architecture.yml with the older `adapter: js` rewritten as `adapters: [js]`; the rest of the text is kept byte for byte.
 * Null when there is nothing to migrate (already a list, or a form this can't rewrite safely: check then explains).
 * @param {string} text
 * @returns {string | null}
 */
export function migrateAdapterKey(text) {
  if (/^adapters:/m.test(text)) return null;
  return OLD_ADAPTER_KEY_RE.test(text) ? text.replace(OLD_ADAPTER_KEY_RE, (_, _q, name, comment = '') => `adapters: [${name}]${comment}`) : null;
}

/**
 * What sync should produce, from the sources. No writes.
 * @param {string} root
 * @param {{ skipClaude?: boolean, ignore?: Set<string> }} [opts] `ignore`: user files to treat as absent (legacy copies)
 * @returns {{ files: { path: string, content: string, source: string }[], notes: import('@agentreins/core').Note[], problems: string[] }}
 */
export function planSync(root, opts = {}) {
  const files = [];
  const problems = [];
  const ignore = opts.ignore ?? new Set();
  const tpl = templatesDir();
  const coreBase = path.join(tpl, '.reins', 'core');

  // 1. core files: .reins/core/** (managed from templates/.reins/core)
  if (existsSync(coreBase)) {
    for (const f of listFiles(tpl, '.reins/core')) {
      const content = readFileSync(path.join(tpl, f), 'utf8');
      files.push({ path: f, content, source: `templates/${f}` });
    }
  }

  // 1b. a README in each override folder, so people know where their own skills, agents and policies go
  for (const dir of LEGACY_DIRS) {
    const rel = `${REINS_DIR}/${dir}/README.md`;
    if (existsSync(path.join(tpl, rel))) files.push({ path: rel, content: readFileSync(path.join(tpl, rel), 'utf8'), source: `templates/${rel}` });
  }

  // 2. Claude Code adapter: skills and agents are generated only when enabled.
  if (!opts.skipClaude) {
    // skills: base from templates/.reins/core/skills, overridable in .reins/skills
    const coreSkillsDir = path.join(coreBase, 'skills');
    const userSkillsDir = path.join(root, REINS_DIR, 'skills');
    const skillNames = new Set();
    if (existsSync(coreSkillsDir)) {
      for (const name of readdirSync(coreSkillsDir).sort()) {
        if (statSync(path.join(coreSkillsDir, name)).isDirectory()) skillNames.add(name);
      }
    }
    if (existsSync(userSkillsDir)) {
      for (const name of readdirSync(userSkillsDir).sort()) {
        if (statSync(path.join(userSkillsDir, name)).isDirectory()) skillNames.add(name);
      }
    }

    for (const name of [...skillNames].sort()) {
      const userSrc = `${REINS_DIR}/skills/${name}`;
      const coreSrc = `${REINS_DIR}/core/skills/${name}`;
      const isUser = existsSync(path.join(root, userSrc, 'SKILL.md')) && !ignore.has(`${userSrc}/SKILL.md`);
      if (!isUser && !existsSync(path.join(tpl, coreSrc))) continue; // only a legacy copy of a skill reins no longer ships
      const chosenSrc = isUser ? userSrc : coreSrc;
      const baseDir = isUser ? root : tpl;

      if (!existsSync(path.join(baseDir, chosenSrc, 'SKILL.md'))) {
        problems.push(`${chosenSrc}: no SKILL.md, skipped.`);
        continue;
      }
      const outDir = `.claude/skills/${PREFIX}${name}`;
      for (const f of listFiles(baseDir, chosenSrc).filter((x) => !ignore.has(x))) {
        const rel = f.slice(chosenSrc.length + 1);
        let content = readFileSync(path.join(baseDir, f), 'utf8');
        if (rel === 'SKILL.md') {
          let fm;
          try {
            fm = parseFrontmatter(content);
          } catch (e) {
            problems.push(`${f}: frontmatter is not valid YAML; skipped.`);
            continue;
          }
          if (!fm?.data.description) {
            problems.push(`${f}: frontmatter needs a "description" (it is how the agent decides to load the skill); skipped.`);
            continue;
          }
          content = `---\nname: ${PREFIX}${name}\ndescription: ${yamlScalar(String(fm.data.description))}\n---\n${generatedNote(f)}\n${fm.body.replace(/^\n+/, '')}`;
        }
        files.push({ path: `${outDir}/${rel}`, content, source: f });
      }
    }

    // 3. agents: base from templates/.reins/core/agents, overridable in .reins/agents
    const coreAgentsDir = path.join(coreBase, 'agents');
    const userAgentsDir = path.join(root, REINS_DIR, 'agents');
    const agentNames = new Set();
    if (existsSync(coreAgentsDir)) {
      for (const name of readdirSync(coreAgentsDir).filter((n) => n.endsWith('.md')).sort()) {
        agentNames.add(name);
      }
    }
    if (existsSync(userAgentsDir)) {
      for (const name of readdirSync(userAgentsDir).filter((n) => n.endsWith('.md') && n !== 'README.md').sort()) {
        agentNames.add(name);
      }
    }

    for (const name of [...agentNames].sort()) {
      const userSrc = `${REINS_DIR}/agents/${name}`;
      const coreSrc = `${REINS_DIR}/core/agents/${name}`;
      const isUser = existsSync(path.join(root, userSrc)) && !ignore.has(userSrc);
      if (!isUser && !existsSync(path.join(tpl, coreSrc))) continue;
      const chosenSrc = isUser ? userSrc : coreSrc;
      const baseDir = isUser ? root : tpl;

      let fm;
      try {
        fm = parseFrontmatter(readFileSync(path.join(baseDir, chosenSrc), 'utf8'));
      } catch {
        problems.push(`${chosenSrc}: frontmatter is not valid YAML; skipped.`);
        continue;
      }
      if (!fm?.data.description) {
        problems.push(`${chosenSrc}: frontmatter needs a "description"; skipped.`);
        continue;
      }
      const tools = Array.isArray(fm.data.tools) ? fm.data.tools.join(', ') : fm.data.tools;
      const header = [`name: ${PREFIX}${name.replace(/\.md$/, '')}`, `description: ${yamlScalar(String(fm.data.description))}`, ...(tools ? [`tools: ${tools}`] : [])];
      files.push({ path: `.claude/agents/${PREFIX}${name}`, content: `---\n${header.join('\n')}\n---\n${generatedNote(chosenSrc)}\n${fm.body.replace(/^\n+/, '')}`, source: chosenSrc });
    }

    // 4. CLAUDE.md, only when missing (otherwise it belongs to the repo)
    if (!existsSync(path.join(root, 'CLAUDE.md'))) files.push({ path: 'CLAUDE.md', content: readTemplate('CLAUDE.md'), source: 'templates/CLAUDE.md' });
  }

  // 5. notes index
  const { notes, problems: noteProblems } = loadNotes(root);
  problems.push(...noteProblems);
  return { files, notes, problems };
}

/** Paths shown per note in the AGENTS.md index. */
export const MAX_INDEX_PATHS = 2;

/**
 * One line per module note. The notes of a module's parts (`.reins/notes/<module>/<part>.md`) go on the line of
 * `<module>.md`, so AGENTS.md does not grow a line per part; the notes hook delivers both anyway. A part whose
 * module note is missing gets a line of its own.
 * @param {{ file: string, paths: string[] }[]} notes
 */
export function renderNotesIndex(notes) {
  const files = new Set(notes.map((n) => n.file));
  const grouped = (n) => {
    const parent = parentNoteFile(n.file);
    return parent !== null && files.has(parent);
  };
  return notes.filter((n) => !grouped(n)).map((n) => {
    const own = notes.filter((x) => grouped(x) && parentNoteFile(x.file) === n.file);
    const folder = n.file.replace(/\.md$/, '/');
    const tail = own.length ? `; parts in \`${folder}\`: ${own.map((x) => x.file.slice(folder.length, -3)).join(', ')}` : '';
    // AGENTS.md is read on every session: a few paths say where the module is, the note itself has them all
    const shown = n.paths.slice(0, MAX_INDEX_PATHS).map((p) => `\`${p}\``).join(', ');
    const more = n.paths.length > MAX_INDEX_PATHS ? ` (+${n.paths.length - MAX_INDEX_PATHS} more)` : '';
    return `- ${shown}${more} → \`${n.file}\`${tail}\n`;
  }).join('');
}

/**
 * The notes block that fits in `budget` lines. It always starts with how to get a file's notes with
 * `reins notes <path…>`: the hook only fires on Read/Edit/Write, and agents also read code from the shell or
 * other tools. Then the path → note index when it fits; otherwise only the count. Doctor's `agents-size` limit
 * counts every line of AGENTS.md, so sync must never write a block that breaks it.
 * @param {{ file: string, paths: string[] }[]} notes
 * @param {number} budget lines available for the block
 * @returns {{ block: string, compact: boolean }}
 */
export function fitNotesIndex(notes, budget) {
  if (notes.length === 0) return { block: '', compact: false };
  const how = 'Before changing a file, run `npx reins notes <path…>` to get its module notes (the hook delivers them only on Read/Edit/Write)';
  const index = renderNotesIndex(notes);
  if (1 + index.split('\n').length - 1 <= Math.max(budget, 1)) return { block: `- ${how}. By path:\n${index}`, compact: false };
  return { block: `- ${how}. ${notes.length} notes in \`${REINS_DIR}/notes/\`, too many to list here.\n`, compact: true };
}

/** @returns {{ version: 1, files: Record<string, string>, blocks: Record<string, string>, adapters: { claude: boolean }, settings: { deny: string[], hooks: typeof SETTINGS.hooks }, cursor: { hooks: typeof CURSOR_HOOKS } }} */
export function readManifest(root) {
  const empty = { version: 1, files: {}, blocks: {}, adapters: { claude: true }, settings: { deny: [], hooks: [] }, cursor: { hooks: [] } };
  const text = readText(root, MANIFEST_FILE);
  if (text === null) return empty;
  try {
    const m = JSON.parse(text);
    return {
      ...empty,
      ...m,
      adapters: { ...empty.adapters, ...(m.adapters ?? {}) },
      settings: { ...empty.settings, ...(m.settings ?? {}) },
      cursor: { ...empty.cursor, ...(m.cursor ?? {}) },
    };
  } catch {
    return empty;
  }
}

const hookMatches = (entry, h) => entry?.matcher === h.matcher && entry.hooks?.length === 1 && entry.hooks[0].command === h.command;
const sameHook = (a, b) => a.event === b.event && a.matcher === b.matcher && a.command === b.command;

/**
 * Brings .claude/settings.json in line without reordering anything: removes entries reins added before that
 * are no longer wanted, and appends the wanted ones that are missing. Entries reins didn't add are never touched.
 * @param {string | null} currentText
 * @param {{ deny: string[], hooks: typeof SETTINGS.hooks }} previous what reins owned last time
 * @returns {{ text: string | null, changed: boolean, owned: { deny: string[], hooks: typeof SETTINGS.hooks }, problem: string | null }}
 */
export function mergeSettings(currentText, previous) {
  let settings = {};
  if (currentText !== null) {
    try {
      settings = JSON.parse(currentText);
    } catch (e) {
      return { text: currentText, changed: false, owned: previous, problem: `${SETTINGS_FILE} is not valid JSON (${e.message}); not touched.` };
    }
  }
  let changed = currentText === null;
  const owned = { deny: [], hooks: [] };

  const deny = [...(settings.permissions?.deny ?? [])];
  for (const d of previous.deny) {
    if (!SETTINGS.deny.includes(d) && deny.includes(d)) {
      deny.splice(deny.indexOf(d), 1);
      changed = true;
    }
  }
  for (const d of SETTINGS.deny) {
    if (!deny.includes(d)) {
      deny.push(d);
      owned.deny.push(d);
      changed = true;
    } else if (previous.deny.includes(d)) owned.deny.push(d);
  }

  const hooks = { ...(settings.hooks ?? {}) };
  for (const h of previous.hooks) {
    if (SETTINGS.hooks.some((w) => sameHook(w, h)) || !hooks[h.event]) continue;
    const kept = hooks[h.event].filter((e) => !hookMatches(e, h));
    if (kept.length !== hooks[h.event].length) changed = true;
    if (kept.length) hooks[h.event] = kept;
    else delete hooks[h.event];
  }
  for (const h of SETTINGS.hooks) {
    const list = (hooks[h.event] = [...(hooks[h.event] ?? [])]);
    if (!list.some((e) => hookMatches(e, h))) {
      list.push({ matcher: h.matcher, hooks: [{ type: 'command', command: h.command }] });
      owned.hooks.push(h);
      changed = true;
    } else if (previous.hooks.some((p) => sameHook(p, h))) owned.hooks.push(h);
  }

  if (!changed) return { text: currentText, changed, owned, problem: null };
  settings.permissions = { ...(settings.permissions ?? {}), deny };
  settings.hooks = hooks;
  return { text: `${JSON.stringify(settings, null, 2)}\n`, changed, owned, problem: null };
}

/**
 * Brings .cursor/hooks.json in line, like `mergeSettings`: removes entries reins added before that are no longer
 * wanted, appends the wanted ones that are missing, never touches anything else.
 * @param {string | null} currentText
 * @param {{ hooks: typeof CURSOR_HOOKS }} previous what reins owned last time
 * @returns {{ text: string | null, changed: boolean, owned: { hooks: typeof CURSOR_HOOKS }, problem: string | null }}
 */
export function mergeCursorHooks(currentText, previous) {
  let config = { version: 1, hooks: {} };
  if (currentText !== null) {
    try {
      config = JSON.parse(currentText);
    } catch (e) {
      return { text: currentText, changed: false, owned: previous, problem: `${CURSOR_HOOKS_FILE} is not valid JSON (${e.message}); not touched.` };
    }
  }
  let changed = currentText === null;
  const owned = { hooks: [] };
  const hooks = { ...(config.hooks ?? {}) };
  const same = (a, b) => a.event === b.event && a.command === b.command;
  for (const h of previous.hooks) {
    if (CURSOR_HOOKS.some((w) => same(w, h)) || !hooks[h.event]) continue;
    const kept = hooks[h.event].filter((e) => e?.command !== h.command);
    if (kept.length !== hooks[h.event].length) changed = true;
    if (kept.length) hooks[h.event] = kept;
    else delete hooks[h.event];
  }
  for (const h of CURSOR_HOOKS) {
    const list = (hooks[h.event] = [...(hooks[h.event] ?? [])]);
    if (!list.some((e) => e?.command === h.command)) {
      list.push({ command: h.command });
      owned.hooks.push(h);
      changed = true;
    } else if (previous.hooks.some((p) => same(p, h))) owned.hooks.push(h);
  }
  if (!changed) return { text: currentText, changed, owned, problem: null };
  return { text: `${JSON.stringify({ ...config, version: config.version ?? 1, hooks }, null, 2)}\n`, changed, owned, problem: null };
}

/**
 * Where to make a change instead of editing a generated file. Sources under `templates/` ship inside the reins
 * package and don't exist in the consumer repo, and `.reins/core/` is rewritten too, so neither is a place to edit:
 * point to the override folder when there is one.
 * @param {{ path: string, source: string }} f
 * @returns {string}
 */
export function editHint(f) {
  const fromPackage = f.source.startsWith('templates/');
  const src = fromPackage ? f.source.slice('templates/'.length) : f.source;
  const core = `${REINS_DIR}/core/`;
  const rest = src.startsWith(core) ? src.slice(core.length) : '';
  if (['skills', 'agents', 'review'].includes(rest.split('/')[0])) {
    return `reins rewrites ${src} on every sync; to change it, copy it to ${REINS_DIR}/${rest} and edit that copy`;
  }
  return fromPackage || rest ? 'reins rewrites it on every sync' : `edit ${f.source} instead`;
}

/** Removes empty folders from `dir` up to (not including) `stop`. */
function pruneDirs(root, dir, stop) {
  let d = dir;
  while (d && d !== stop && d.startsWith(`${stop}/`)) {
    const abs = path.join(root, d);
    if (!existsSync(abs) || readdirSync(abs).length) return;
    rmdirSync(abs);
    d = path.posix.dirname(d);
  }
}

/**
 * Runs sync. With `check: true` it writes nothing and reports what differs.
 * @param {string} root
 * @param {{ check?: boolean, claude?: boolean, skipClaude?: boolean }} [opts]
 * @returns {{ changes: string[], warnings: string[], divergences: string[] }}
 */
export function sync(root, opts = {}) {
  const check = Boolean(opts.check);
  const manifest = readManifest(root);
  const skipClaude = opts.skipClaude === true || (opts.claude !== true && manifest.adapters.claude === false);
  const legacy = legacyCopies(root);
  const plan = planSync(root, { skipClaude, ignore: new Set(legacy) });
  const next = { version: 1, files: {}, blocks: {}, adapters: { claude: !skipClaude }, settings: { deny: [], hooks: [] }, cursor: { hooks: [] } };
  const changes = [];
  const warnings = [...plan.problems];
  const divergences = [];
  const write = (rel, content) => {
    if (check) return;
    mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    writeFileSync(path.join(root, rel), content);
  };

  // 1. generated files
  const expected = new Set(plan.files.map((f) => f.path));
  for (const f of plan.files) {
    const disk = readText(root, f.path);
    const owned = f.path in manifest.files;
    if (disk === f.content) {
      next.files[f.path] = sha(f.content); // up to date (adopted if it was identical but unrecorded)
      continue;
    }
    if (disk !== null && !owned) {
      warnings.push(`${f.path} exists and was not generated by reins; not touched. Rename the source in ${posix(path.dirname(f.source))} or remove the file.`);
      if (check) divergences.push(`${f.path}: exists but was not generated by reins`);
      continue;
    }
    next.files[f.path] = sha(f.content);
    if (disk === null) {
      changes.push(`created ${f.path}`);
      divergences.push(`${f.path}: missing (source: ${f.source})`);
    } else if (sha(disk) !== manifest.files[f.path]) {
      changes.push(`overwrote ${f.path} (it had manual changes; ${editHint(f)})`);
      divergences.push(`${f.path}: edited by hand (source: ${f.source})`);
    } else {
      changes.push(`updated ${f.path}`);
      divergences.push(`${f.path}: out of date with ${f.source}`);
    }
    write(f.path, f.content);
  }
  // files reins generated before but whose source is gone
  for (const [rel, hash] of Object.entries(manifest.files)) {
    if (expected.has(rel)) continue;
    if (skipClaude && (rel === 'CLAUDE.md' || rel.startsWith('.claude/'))) {
      next.files[rel] = hash;
      continue;
    }
    if (rel === 'CLAUDE.md') continue; // created once, then it belongs to the repo
    const disk = readText(root, rel);
    if (disk === null) continue;
    if (sha(disk) !== hash) {
      warnings.push(`${rel}: its source is gone but it has manual changes; kept and no longer managed by reins.`);
      continue;
    }
    changes.push(`removed ${rel} (source deleted)`);
    divergences.push(`${rel}: its source no longer exists`);
    if (!check) {
      unlinkSync(path.join(root, rel));
      pruneDirs(root, path.posix.dirname(rel), '.claude');
    }
  }
  if (manifest.files['CLAUDE.md'] && !expected.has('CLAUDE.md')) next.files['CLAUDE.md'] = manifest.files['CLAUDE.md'];

  // unmodified copies of defaults an older reins install put in .reins/: the synced .reins/core/ replaces them
  for (const rel of legacy) {
    changes.push(`removed ${rel} (unmodified copy of a reins default; it now lives in ${REINS_DIR}/core/)`);
    divergences.push(`${rel}: unmodified copy of a reins default (now in ${REINS_DIR}/core/)`);
    if (!check) {
      unlinkSync(path.join(root, rel));
      pruneDirs(root, path.posix.dirname(rel), REINS_DIR);
    }
  }

  // architecture.yml from reins <= 0.11.0: the only edit sync makes to it, a format migration shown in the diff
  const arch = readText(root, ARCHITECTURE_FILE);
  const archMigrated = arch === null ? null : migrateAdapterKey(arch);
  if (archMigrated !== null) {
    changes.push(`migrated ${ARCHITECTURE_FILE}: \`adapter: <name>\` is now \`adapters: [<name>]\` (review it in the diff)`);
    divergences.push(`${ARCHITECTURE_FILE}: uses the older \`adapter:\` key`);
    write(ARCHITECTURE_FILE, archMigrated);
  }

  // 2. AGENTS.md: create if missing, keep rules block, then keep the notes index block
  let agents = readText(root, 'AGENTS.md');
  const wasMissing = agents === null;
  if (wasMissing) {
    agents = renderAgentsMd(root, (s) => runScriptCommand(root, s));
    changes.push('created AGENTS.md');
    divergences.push('AGENTS.md: missing');
  }
  const migrated = wasMissing ? null : migrateLegacyRules(agents);
  if (migrated !== null) {
    agents = migrated;
    changes.push('replaced the rules an older reins wrote in AGENTS.md with the reins:rules block');
    divergences.push('AGENTS.md: rules written by an older reins, not in a reins:rules block');
  }

  let rules = '';
  try {
    rules = readTemplate('.reins/core/rules.md');
  } catch {
    /* fallback if missing */
  }

  const rm = RULES_BLOCK_RE.exec(agents);
  if (rm) {
    if (rules && rm[2] !== rules) {
      agents = agents.replace(RULES_BLOCK_RE, `$1${rules}$3`);
      if (!wasMissing && migrated === null) {
        changes.push('updated the reins rules in AGENTS.md');
        divergences.push('AGENTS.md: reins rules out of date with .reins/core/rules.md');
      }
    }
    next.blocks['AGENTS.md#rules'] = sha(rules);
  } else if (rules) {
    warnings.push('AGENTS.md has no reins rules markers. Add `<!-- reins:rules:start -->` and `<!-- reins:rules:end -->` where the rules should go (and remove any hand-copied reins rules), or run `reins install` to append them.');
    if (check) divergences.push('AGENTS.md: reins rules markers missing');
  }

  const m = NOTES_BLOCK_RE.exec(agents);
  let notesBlock = '';
  if (m) {
    let maxLines = DOCTOR_DEFAULTS.agents_md.max_lines;
    try {
      maxLines = readDoctorConfig(root).agents_md.max_lines;
    } catch (e) {
      warnings.push(`${e.message} Using the default AGENTS.md limit (${maxLines} lines).`);
    }
    const fixed = countLines(agents.replace(NOTES_BLOCK_RE, '$1$3'));
    const fit = fitNotesIndex(plan.notes, maxLines - fixed);
    notesBlock = fit.block;
    if (countLines(agents.replace(NOTES_BLOCK_RE, `$1${notesBlock}$3`)) > maxLines) {
      warnings.push(`AGENTS.md has ${fixed} lines without the notes index; the limit is ${maxLines} (.reins/doctor.yml). Move what is not needed always to a policy or a note.`);
    } else if (fit.compact && m[2] !== notesBlock) {
      warnings.push(`The notes block in AGENTS.md only says how to get the notes: one line per note would take it over its ${maxLines}-line limit.`);
    }
  }
  if (!m) {
    warnings.push('AGENTS.md has no notes index markers; run `reins install` to append them, or add `<!-- reins:notes:start -->` and `<!-- reins:notes:end -->` where the index should go.');
    if (check) divergences.push('AGENTS.md: notes index markers missing');
  } else {
    if (m[2] !== notesBlock) {
      agents = agents.replace(NOTES_BLOCK_RE, `$1${notesBlock}$3`);
      if (!wasMissing) {
        changes.push('updated the notes index in AGENTS.md');
        divergences.push('AGENTS.md: notes index out of date with .reins/notes/');
      }
    }
    next.blocks['AGENTS.md#notes'] = sha(notesBlock);
  }
  if (agents !== readText(root, 'AGENTS.md')) write('AGENTS.md', agents);

  // 3. Optional Claude Code settings adapter (Cursor runs the same hooks; it only needs a native session start trigger)
  if (skipClaude) {
    next.settings = manifest.settings;
    next.cursor = manifest.cursor;
  } else {
    const currentCursor = readText(root, CURSOR_HOOKS_FILE);
    const cursor = mergeCursorHooks(currentCursor, manifest.cursor);
    if (cursor.problem) {
      warnings.push(cursor.problem);
      if (check) divergences.push(`${CURSOR_HOOKS_FILE}: not valid JSON`);
      next.cursor = manifest.cursor;
    } else {
      next.cursor = cursor.owned;
      if (cursor.changed) {
        changes.push(`${currentCursor === null ? 'created' : 'updated'} ${CURSOR_HOOKS_FILE} (Cursor session start runs reins' hooks)`);
        divergences.push(`${CURSOR_HOOKS_FILE}: reins session start trigger missing or out of date`);
        write(CURSOR_HOOKS_FILE, cursor.text);
      }
    }
    const currentSettings = readText(root, SETTINGS_FILE);
    const merged = mergeSettings(currentSettings, manifest.settings);
    if (merged.problem) {
      warnings.push(merged.problem);
      if (check) divergences.push(`${SETTINGS_FILE}: not valid JSON`);
      next.settings = manifest.settings;
    } else {
      next.settings = merged.owned;
      if (merged.changed) {
        changes.push(`${currentSettings === null ? 'created' : 'updated'} ${SETTINGS_FILE} (git permissions, notes hook)`);
        divergences.push(`${SETTINGS_FILE}: reins permissions or hook missing or out of date`);
        write(SETTINGS_FILE, merged.text);
      }
    }
  }

  // 4. manifest
  const manifestText = `${JSON.stringify({ version: 1, note: 'Generated by reins sync. Lists what reins owns; do not edit.', ...next }, null, 2)}\n`;
  const prevText = readText(root, MANIFEST_FILE);
  const normalize = (t) => {
    try {
      const { note, ...rest } = JSON.parse(t);
      return JSON.stringify(rest);
    } catch {
      return t;
    }
  };
  if (prevText === null || normalize(prevText) !== normalize(manifestText)) {
    if (!check) write(MANIFEST_FILE, manifestText);
    else if (prevText === null) divergences.push(`${MANIFEST_FILE}: missing (run reins sync)`);
  }

  return { changes, warnings, divergences: check ? divergences : [] };
}

// harness sync: generates the tool layer (layer 3) from the sources in .harness/.
//
//   .harness/skills/<n>/   -> .claude/skills/harness-<n>/       (SKILL.md gets name: harness-<n>)
//   .harness/agents/<n>.md -> .claude/agents/harness-<n>.md     (Claude Code subagent frontmatter)
//   .harness/notes/*.md    -> notes index block inside AGENTS.md
//   (fixed)                -> hooks (notes, resume) + git permissions inside .claude/settings.json
//   templates              -> AGENTS.md and CLAUDE.md, only when missing
//
// Everything it writes is recorded in .harness/.generated.json, and it only ever touches what is recorded there:
// third-party skills, agents and settings are never overwritten or deleted.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from '@harness/core';
import { HARNESS_DIR, runScriptCommand } from '../context.js';
import { loadNotes, readText } from '../project.js';
import { readTemplate, renderAgentsMd } from '../templates.js';

export const MANIFEST_FILE = `${HARNESS_DIR}/.generated.json`;
export const SETTINGS_FILE = '.claude/settings.json';
export const PREFIX = 'harness-';
/** What `harness install` appends to an AGENTS.md that has no notes index yet. */
export const NOTES_BLOCK_SECTION = '## Module notes\n- Before touching these paths, read their note:\n<!-- harness:notes:start (generated by harness sync) -->\n<!-- harness:notes:end -->\n';
export const NOTES_BLOCK_RE = /(<!-- harness:notes:start[^>]*-->\r?\n)([\s\S]*?)(<!-- harness:notes:end -->)/;

/** Permissions and hooks harness adds to .claude/settings.json. */
export const SETTINGS = Object.freeze({
  deny: ['Bash(git commit:*)', 'Bash(git push:*)'],
  hooks: [
    { event: 'PreToolUse', matcher: 'Read|Edit|Write|MultiEdit', command: '"$CLAUDE_PROJECT_DIR"/node_modules/.bin/harness notes --hook' },
    { event: 'SessionStart', matcher: 'startup|compact|clear', command: '"$CLAUDE_PROJECT_DIR"/node_modules/.bin/harness resume --hook' },
  ],
});

const sha = (s) => createHash('sha256').update(s).digest('hex');
const posix = (p) => p.split(path.sep).join('/');
const generatedNote = (source) => `<!-- Generated by harness sync from ${source}. Edit the source and run \`harness sync\`. -->`;
const yamlScalar = (s) => (/^[\w .,()/-]+$/.test(s) && !/^\s|\s$/.test(s) ? s : JSON.stringify(s));

/** All files under a folder, repo-relative. */
function listFiles(root, rel) {
  const abs = path.join(root, rel);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const name of readdirSync(abs).sort()) {
    const r = `${rel}/${name}`;
    if (statSync(path.join(root, r)).isDirectory()) out.push(...listFiles(root, r));
    else out.push(r);
  }
  return out;
}

/**
 * What sync should produce, from the sources. No writes.
 * @param {string} root
 * @returns {{ files: { path: string, content: string, source: string }[], notesBlock: string, problems: string[] }}
 */
export function planSync(root) {
  const files = [];
  const problems = [];

  // skills
  const skillsDir = `${HARNESS_DIR}/skills`;
  if (existsSync(path.join(root, skillsDir))) {
    for (const name of readdirSync(path.join(root, skillsDir)).sort()) {
      const src = `${skillsDir}/${name}`;
      if (!statSync(path.join(root, src)).isDirectory()) continue;
      if (!existsSync(path.join(root, src, 'SKILL.md'))) {
        problems.push(`${src}: no SKILL.md, skipped.`);
        continue;
      }
      const outDir = `.claude/skills/${PREFIX}${name}`;
      for (const f of listFiles(root, src)) {
        const rel = f.slice(src.length + 1);
        let content = readFileSync(path.join(root, f), 'utf8');
        if (rel === 'SKILL.md') {
          let fm;
          try {
            fm = parseFrontmatter(content);
          } catch (e) {
            problems.push(`${f}: frontmatter is not valid YAML; skipped.`);
            continue;
          }
          if (!fm?.data.description) {
            problems.push(`${f}: frontmatter needs a "description" (it is how the agent decides to load the skill); skipped.`);
            continue;
          }
          content = `---\nname: ${PREFIX}${name}\ndescription: ${yamlScalar(String(fm.data.description))}\n---\n${generatedNote(f)}\n${fm.body.replace(/^\n+/, '')}`;
        }
        files.push({ path: `${outDir}/${rel}`, content, source: f });
      }
    }
  }

  // agents
  const agentsDir = `${HARNESS_DIR}/agents`;
  if (existsSync(path.join(root, agentsDir))) {
    for (const name of readdirSync(path.join(root, agentsDir)).filter((n) => n.endsWith('.md')).sort()) {
      const src = `${agentsDir}/${name}`;
      let fm;
      try {
        fm = parseFrontmatter(readFileSync(path.join(root, src), 'utf8'));
      } catch {
        problems.push(`${src}: frontmatter is not valid YAML; skipped.`);
        continue;
      }
      if (!fm?.data.description) {
        problems.push(`${src}: frontmatter needs a "description"; skipped.`);
        continue;
      }
      const tools = Array.isArray(fm.data.tools) ? fm.data.tools.join(', ') : fm.data.tools;
      const header = [`name: ${PREFIX}${name.replace(/\.md$/, '')}`, `description: ${yamlScalar(String(fm.data.description))}`, ...(tools ? [`tools: ${tools}`] : [])];
      files.push({ path: `.claude/agents/${PREFIX}${name}`, content: `---\n${header.join('\n')}\n---\n${generatedNote(src)}\n${fm.body.replace(/^\n+/, '')}`, source: src });
    }
  }

  // CLAUDE.md, only when missing (otherwise it belongs to the repo)
  if (!existsSync(path.join(root, 'CLAUDE.md'))) files.push({ path: 'CLAUDE.md', content: readTemplate('CLAUDE.md'), source: 'templates/CLAUDE.md' });

  // notes index
  const { notes, problems: noteProblems } = loadNotes(root);
  problems.push(...noteProblems);
  const notesBlock = notes.map((n) => `- ${n.paths.map((p) => `\`${p}\``).join(', ')} → \`${n.file}\`\n`).join('');

  return { files, notesBlock, problems };
}

/** @returns {{ version: 1, files: Record<string, string>, blocks: Record<string, string>, settings: { deny: string[], hooks: typeof SETTINGS.hooks } }} */
export function readManifest(root) {
  const empty = { version: 1, files: {}, blocks: {}, settings: { deny: [], hooks: [] } };
  const text = readText(root, MANIFEST_FILE);
  if (text === null) return empty;
  try {
    const m = JSON.parse(text);
    return { ...empty, ...m, settings: { ...empty.settings, ...(m.settings ?? {}) } };
  } catch {
    return empty;
  }
}

const hookMatches = (entry, h) => entry?.matcher === h.matcher && entry.hooks?.length === 1 && entry.hooks[0].command === h.command;
const sameHook = (a, b) => a.event === b.event && a.matcher === b.matcher && a.command === b.command;

/**
 * Brings .claude/settings.json in line without reordering anything: removes entries harness added before that
 * are no longer wanted, and appends the wanted ones that are missing. Entries harness didn't add are never touched.
 * @param {string | null} currentText
 * @param {{ deny: string[], hooks: typeof SETTINGS.hooks }} previous what harness owned last time
 * @returns {{ text: string | null, changed: boolean, owned: { deny: string[], hooks: typeof SETTINGS.hooks }, problem: string | null }}
 */
export function mergeSettings(currentText, previous) {
  let settings = {};
  if (currentText !== null) {
    try {
      settings = JSON.parse(currentText);
    } catch (e) {
      return { text: currentText, changed: false, owned: previous, problem: `${SETTINGS_FILE} is not valid JSON (${e.message}); not touched.` };
    }
  }
  let changed = currentText === null;
  const owned = { deny: [], hooks: [] };

  const deny = [...(settings.permissions?.deny ?? [])];
  for (const d of previous.deny) {
    if (!SETTINGS.deny.includes(d) && deny.includes(d)) {
      deny.splice(deny.indexOf(d), 1);
      changed = true;
    }
  }
  for (const d of SETTINGS.deny) {
    if (!deny.includes(d)) {
      deny.push(d);
      owned.deny.push(d);
      changed = true;
    } else if (previous.deny.includes(d)) owned.deny.push(d);
  }

  const hooks = { ...(settings.hooks ?? {}) };
  for (const h of previous.hooks) {
    if (SETTINGS.hooks.some((w) => sameHook(w, h)) || !hooks[h.event]) continue;
    const kept = hooks[h.event].filter((e) => !hookMatches(e, h));
    if (kept.length !== hooks[h.event].length) changed = true;
    if (kept.length) hooks[h.event] = kept;
    else delete hooks[h.event];
  }
  for (const h of SETTINGS.hooks) {
    const list = (hooks[h.event] = [...(hooks[h.event] ?? [])]);
    if (!list.some((e) => hookMatches(e, h))) {
      list.push({ matcher: h.matcher, hooks: [{ type: 'command', command: h.command }] });
      owned.hooks.push(h);
      changed = true;
    } else if (previous.hooks.some((p) => sameHook(p, h))) owned.hooks.push(h);
  }

  if (!changed) return { text: currentText, changed, owned, problem: null };
  settings.permissions = { ...(settings.permissions ?? {}), deny };
  settings.hooks = hooks;
  return { text: `${JSON.stringify(settings, null, 2)}\n`, changed, owned, problem: null };
}

/** Removes empty folders from `dir` up to (not including) `stop`. */
function pruneDirs(root, dir, stop) {
  let d = dir;
  while (d && d !== stop && d.startsWith(`${stop}/`)) {
    const abs = path.join(root, d);
    if (!existsSync(abs) || readdirSync(abs).length) return;
    rmdirSync(abs);
    d = path.posix.dirname(d);
  }
}

/**
 * Runs sync. With `check: true` it writes nothing and reports what differs.
 * @param {string} root
 * @param {{ check?: boolean }} [opts]
 * @returns {{ changes: string[], warnings: string[], divergences: string[] }}
 */
export function sync(root, opts = {}) {
  const check = Boolean(opts.check);
  const plan = planSync(root);
  const manifest = readManifest(root);
  const next = { version: 1, files: {}, blocks: {}, settings: { deny: [], hooks: [] } };
  const changes = [];
  const warnings = [...plan.problems];
  const divergences = [];
  const write = (rel, content) => {
    if (check) return;
    mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    writeFileSync(path.join(root, rel), content);
  };

  // 1. generated files
  const expected = new Set(plan.files.map((f) => f.path));
  for (const f of plan.files) {
    const disk = readText(root, f.path);
    const owned = f.path in manifest.files;
    if (disk === f.content) {
      next.files[f.path] = sha(f.content); // up to date (adopted if it was identical but unrecorded)
      continue;
    }
    if (disk !== null && !owned) {
      warnings.push(`${f.path} exists and was not generated by harness; not touched. Rename the source in ${posix(path.dirname(f.source))} or remove the file.`);
      if (check) divergences.push(`${f.path}: exists but was not generated by harness`);
      continue;
    }
    next.files[f.path] = sha(f.content);
    if (disk === null) {
      changes.push(`created ${f.path}`);
      divergences.push(`${f.path}: missing (source: ${f.source})`);
    } else if (sha(disk) !== manifest.files[f.path]) {
      changes.push(`overwrote ${f.path} (it had manual changes; edit ${f.source} instead)`);
      divergences.push(`${f.path}: edited by hand (source: ${f.source})`);
    } else {
      changes.push(`updated ${f.path}`);
      divergences.push(`${f.path}: out of date with ${f.source}`);
    }
    write(f.path, f.content);
  }
  // files harness generated before but whose source is gone
  for (const [rel, hash] of Object.entries(manifest.files)) {
    if (expected.has(rel)) continue;
    if (rel === 'CLAUDE.md') continue; // created once, then it belongs to the repo
    const disk = readText(root, rel);
    if (disk === null) continue;
    if (sha(disk) !== hash) {
      warnings.push(`${rel}: its source is gone but it has manual changes; kept and no longer managed by harness.`);
      continue;
    }
    changes.push(`removed ${rel} (source deleted)`);
    divergences.push(`${rel}: its source no longer exists`);
    if (!check) {
      unlinkSync(path.join(root, rel));
      pruneDirs(root, path.posix.dirname(rel), '.claude');
    }
  }
  if (manifest.files['CLAUDE.md'] && !expected.has('CLAUDE.md')) next.files['CLAUDE.md'] = manifest.files['CLAUDE.md'];

  // 2. AGENTS.md: create if missing, then keep the notes index block
  let agents = readText(root, 'AGENTS.md');
  if (agents === null) {
    agents = renderAgentsMd(root, (s) => runScriptCommand(root, s));
    changes.push('created AGENTS.md');
    divergences.push('AGENTS.md: missing');
  }
  const m = NOTES_BLOCK_RE.exec(agents);
  if (!m) {
    warnings.push('AGENTS.md has no notes index markers; run `harness install` to append them, or add `<!-- harness:notes:start -->` and `<!-- harness:notes:end -->` where the index should go.');
    if (check) divergences.push('AGENTS.md: notes index markers missing');
  } else {
    if (m[2] !== plan.notesBlock) {
      agents = agents.replace(NOTES_BLOCK_RE, `$1${plan.notesBlock}$3`);
      changes.push('updated the notes index in AGENTS.md');
      divergences.push('AGENTS.md: notes index out of date with .harness/notes/');
    }
    next.blocks['AGENTS.md#notes'] = sha(plan.notesBlock);
  }
  if (agents !== readText(root, 'AGENTS.md')) write('AGENTS.md', agents);

  // 3. .claude/settings.json
  const currentSettings = readText(root, SETTINGS_FILE);
  const merged = mergeSettings(currentSettings, manifest.settings);
  if (merged.problem) {
    warnings.push(merged.problem);
    if (check) divergences.push(`${SETTINGS_FILE}: not valid JSON`);
    next.settings = manifest.settings;
  } else {
    next.settings = merged.owned;
    if (merged.changed) {
      changes.push(`${currentSettings === null ? 'created' : 'updated'} ${SETTINGS_FILE} (git permissions, notes hook)`);
      divergences.push(`${SETTINGS_FILE}: harness permissions or hook missing or out of date`);
      write(SETTINGS_FILE, merged.text);
    }
  }

  // 4. manifest
  const manifestText = `${JSON.stringify({ version: 1, note: 'Generated by harness sync. Lists what harness owns; do not edit.', ...next }, null, 2)}\n`;
  const prevText = readText(root, MANIFEST_FILE);
  const normalize = (t) => {
    try {
      const { note, ...rest } = JSON.parse(t);
      return JSON.stringify(rest);
    } catch {
      return t;
    }
  };
  if (prevText === null || normalize(prevText) !== normalize(manifestText)) {
    if (!check) write(MANIFEST_FILE, manifestText);
    else if (prevText === null) divergences.push(`${MANIFEST_FILE}: missing (run harness sync)`);
  }

  return { changes, warnings, divergences: check ? divergences : [] };
}

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { cli, exampleRepo, tempDir } from './helpers.js';

const FILES = ['.reins/architecture.yml', '.reins/baseline.json', '.reins/init-report.md'];
const read = (dir, f) => readFileSync(path.join(dir, f), 'utf8');

for (const [name, expected] of [
  ['vite-react', { layers: 'app > features > components > shared', domains: 'cart, catalog', frozen: 3 }],
  ['next-app', { layers: 'app > features > components > shared', domains: 'billing, orders', frozen: 4 }],
]) {
  test(`${name}: init drafts the plan and check passes right after`, async () => {
    const dir = exampleRepo(name, { keepReins: false });
    const r = await cli(dir, ['init']);
    assert.equal(r.code, 0, r.stderr);
    assert.match(r.stdout, new RegExp(`Layers: ${expected.layers} · Domains: ${expected.domains}`));
    assert.match(r.stdout, new RegExp(`${expected.frozen} existing violations frozen`));
    for (const f of FILES) assert.ok(existsSync(path.join(dir, f)), f);

    const check = await cli(dir, ['check']);
    assert.equal(check.code, 0, check.stdout + check.stderr);
    assert.match(check.stdout, new RegExp(`no new violations · ${expected.frozen} in baseline`));
  });
}

test('next-app: the draft proposes TS settings and the Next rule; the report lists cycles, doubtful deps and orphans', async () => {
  const dir = exampleRepo('next-app', { keepReins: false });
  await cli(dir, ['init']);
  const yml = read(dir, '.reins/architecture.yml');
  assert.match(yml, /- \{ id: layer-direction, severity: error, ignore_kinds: \[type\] \}/);
  assert.match(yml, /- \{ id: next-server-client, severity: warn \}/);
  assert.match(yml, /orders: \{ paths: \["src\/features\/orders\/\*\*"\], public_api: \["src\/features\/orders\/index\.ts"\] \}/);
  const report = read(dir, '.reins/init-report.md');
  assert.match(report, /## Cycles\n\n- src\/lib\/date\.ts → src\/lib\/time\.ts → src\/lib\/date\.ts/);
  assert.match(report, /`domain-boundary` src\/app\/orders\/page\.tsx → src\/features\/billing\/tax\.ts/);
  assert.match(report, /## Orphans\n\n[^#]*`src\/lib\/unused\.ts`/);
  assert.doesNotMatch(report, /`src\/app\/page\.tsx`/, 'Next entry points are not orphans');
});


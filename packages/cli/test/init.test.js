const FILES = ['.reins/architecture.yml', '.reins/baseline.json', '.reins/init-report.md'];
const read = (dir, f) => readFileSync(path.join(dir, f), 'utf8');

for (const [name, expected] of [
  ['vite-react', { layers: 'app > features > components > shared', domains: 'cart, catalog', frozen: 3 }],
  ['next-app', { layers: 'app > features > components > shared', domains: 'billing, orders', frozen: 4 }],
]) {
  test(`${name}: init drafts the plan and check passes right after`, async () => {
    const dir = exampleRepo(name, { keepReins: false });
    const r = await cli(dir, ['init']);
    assert.equal(r.code, 0, r.stderr);
    assert.match(r.stdout, new RegExp(`Layers: ${expected.layers} · Domains: ${expected.domains}`));
    assert.match(r.stdout, new RegExp(`${expected.frozen} existing violations frozen`));
    for (const f of FILES) assert.ok(existsSync(path.join(dir, f)), f);

    const check = await cli(dir, ['check']);
    assert.equal(check.code, 0, check.stdout + check.stderr);
    assert.match(check.stdout, new RegExp(`no new violations · ${expected.frozen} in baseline`));
  });
}


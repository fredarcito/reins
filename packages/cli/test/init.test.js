test('--dry-run writes nothing', async () => {
  const dir = exampleRepo('vite-react', { keepReins: false });
  const r = await cli(dir, ['init', '--dry-run']);
  assert.equal(r.code, 0);
  assert.match(r.stdout, /--- \.reins\/architecture\.yml \(not written\)/);
  assert.match(r.stdout, /# reins init report/);
  for (const f of FILES) assert.equal(existsSync(path.join(dir, f)), false, f);
});

test('never overwrites without confirmation', async () => {
  const dir = exampleRepo('vite-react'); // has its own architecture.yml
  const before = read(dir, '.reins/architecture.yml');

  const noTty = await cli(dir, ['init']); // no terminal to ask: refuse
  assert.equal(noTty.code, 2);
  assert.match(noTty.stderr, /already exists\. Overwrite with the new draft\?\nRe-run with --force/);
  assert.equal(read(dir, '.reins/architecture.yml'), before);

  const questions = [];
  const no = await cli(dir, ['init'], { confirm: async (q) => (questions.push(q), false) });
  assert.equal(no.code, 0);
  assert.match(no.stdout, /Nothing written/);
  assert.equal(questions.length, 1);
  assert.equal(read(dir, '.reins/architecture.yml'), before);

  const yes = await cli(dir, ['init'], { confirm: async () => true });
  assert.equal(yes.code, 0);
  assert.notEqual(read(dir, '.reins/architecture.yml'), before);

  writeFileSync(path.join(dir, '.reins/architecture.yml'), before);
  const force = await cli(dir, ['init', '--force']);
  assert.equal(force.code, 0);
  assert.match(read(dir, '.reins/architecture.yml'), /Draft generated by `reins init`/);
});

test('suggests the missing adapter with the repo package manager, installs nothing', async () => {
  const pnpmRepo = tempDir({ 'package.json': '{}', 'pnpm-lock.yaml': '' });
  const r = await cli(pnpmRepo, ['init'], { adapterSearchPaths: [] });
  assert.equal(r.code, 2);
  assert.match(r.stderr, /Adapter "js" is not installed \(looked for @reins\/adapter-js and reins-adapter-js\)\.\nFix: pnpm add -D @reins\/adapter-js/);
  assert.equal(existsSync(path.join(pnpmRepo, 'node_modules')), false);

  const npmRepo = tempDir({ 'package.json': '{}' });
  assert.match((await cli(npmRepo, ['init'], { adapterSearchPaths: [] })).stderr, /Fix: npm install -D @reins\/adapter-js/);

  const noJs = tempDir({ 'Gemfile': '' });
  assert.match((await cli(noJs, ['init'])).stderr, /Could not tell which adapter/);
});


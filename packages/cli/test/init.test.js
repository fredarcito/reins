test('never overwrites without confirmation', async () => {
  const dir = exampleRepo('vite-react'); // has its own architecture.yml
  const before = read(dir, '.reins/architecture.yml');

  const noTty = await cli(dir, ['init']); // no terminal to ask: refuse
  assert.equal(noTty.code, 2);
  assert.match(noTty.stderr, /already exists\. Overwrite with the new draft\?\nRe-run with --force/);
  assert.equal(read(dir, '.reins/architecture.yml'), before);

  const questions = [];
  const no = await cli(dir, ['init'], { confirm: async (q) => (questions.push(q), false) });
  assert.equal(no.code, 0);
  assert.match(no.stdout, /Nothing written/);
  assert.equal(questions.length, 1);
  assert.equal(read(dir, '.reins/architecture.yml'), before);

  const yes = await cli(dir, ['init'], { confirm: async () => true });
  assert.equal(yes.code, 0);
  assert.notEqual(read(dir, '.reins/architecture.yml'), before);

  writeFileSync(path.join(dir, '.reins/architecture.yml'), before);
  const force = await cli(dir, ['init', '--force']);
  assert.equal(force.code, 0);
  assert.match(read(dir, '.reins/architecture.yml'), /Draft generated by `reins init`/);
});

